export type VesselType = "Tanker" | "Bulk Carrier" | "Container Ship" | "General Cargo" | "Other";
export type VesselStatus = "Normal" | "Under Observation" | "In AOI" | "Flagged";
export type RiskLevel = "Low" | "Medium" | "High";

export interface ASIEvent {
  id: string;
  time: string;
  event: string;
  severity: "High" | "Medium" | "Low";
  details?: string;
}

export interface VesselWaypoint {
  id: string;
  time: string;
  label: string;
  coordinates: [number, number];
  speed: number;
  type: "normal" | "loitering" | "alert";
}

export interface VesselRecord {
  id: string;
  name: string;
  type: VesselType;
  imo: string;
  mmsi: string;
  flag: string;
  flagCode: string;
  coordinates: [number, number];
  heading: number;
  speedKnots: number;
  status: VesselStatus;
  distanceKm: number;
  bearingDeg: number;
  riskLevel: RiskLevel;
  asiScore: number;
  lastAis: string;
  eta: string;
  image: string;
  destination: string;
  departurePort: string;
  lengthMeters: number;
  beamMeters: number;
  draftMeters: number;
  asiEvents: ASIEvent[];
  trackWaypoints: VesselWaypoint[];
}

export interface CoastGuardAsset {
  id: string;
  name: string;
  type: string;
  distance: string;
  status: "Operational" | "On Mission";
  callsign: string;
  location: string;
  base: string;
  speed: string;
}

